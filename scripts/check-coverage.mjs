#!/usr/bin/env node
/**
 * Fails if any Ontario Grade 2 expectation has no session, or if any session
 * has no worksheet file on disk. Run it after editing data/sessions.ts.
 *
 * Usage: node scripts/check-coverage.mjs
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const worksheetDir = join(root, "public", "worksheets");

// data/sessions.ts is TypeScript, so strip the types rather than compile.
const raw = readFileSync(join(root, "data", "sessions.ts"), "utf8");
const stripped = raw
  .replace(/^export type[\s\S]*?};$/gm, "")
  .replace(/:\s*Session\[\]/g, "")
  .replace(/:\s*\{\s*code:[\s\S]*?\}\[\]/g, "")
  .replace(/\(code:\s*string\)/g, "(code)")
  .replace(/^export /gm, "");

const sessionDataModule = await import(
  `data:text/javascript,${encodeURIComponent(`${stripped}\nexport { sessions, unitNames, phases, ontarioGrade2Expectations, ontarioGrade2OverallExpectations };`)}`
);

const { sessions, unitNames, phases, ontarioGrade2Expectations, ontarioGrade2OverallExpectations } = sessionDataModule;

const pad = (n) => String(n).padStart(2, "0");
const problems = [];

// 1. Every expectation has at least one session.
const rows = ontarioGrade2Expectations.map((expectation) => {
  const covering = sessions.filter((session) => session.expectations.includes(expectation.code));
  if (covering.length === 0) problems.push(`No session covers ${expectation.code}`);
  return { ...expectation, sessions: covering.map((session) => session.id) };
});

// 1b. And the reverse: every code a session cites is a real expectation. Without
// this the check only ever walked expectations to sessions, so a citation
// pointing at nothing stayed invisible and never reached COVERAGE.md.
const knownCodes = new Set([
  ...ontarioGrade2Expectations.map((expectation) => expectation.code),
  ...ontarioGrade2OverallExpectations.map((expectation) => expectation.code),
]);
for (const session of sessions) {
  for (const code of session.expectations) {
    if (!knownCodes.has(code)) {
      problems.push(`${session.id} cites ${code}, which is not an Ontario Grade 2 expectation`);
    }
  }
}

const overallRows = ontarioGrade2OverallExpectations.map((expectation) => ({
  ...expectation,
  sessions: sessions.filter((session) => session.expectations.includes(expectation.code)).map((s) => s.id),
}));
for (const row of overallRows) {
  if (row.sessions.length === 0) problems.push(`No session covers ${row.code}`);
}

// 2. Every session has a worksheet file, and that file agrees with its name.
for (const session of sessions) {
  const file = `mathnest-unit-${pad(session.unit)}-session-${session.letter.toLowerCase()}.html`;
  const path = join(worksheetDir, file);
  if (!existsSync(path)) {
    problems.push(`Missing worksheet: ${file} (${session.id})`);
    continue;
  }
  const html = readFileSync(path, "utf8");
  const header = html.match(/UNIT (\d{2}) \/\/ SESSION ([A-D])/);
  const wsId = html.match(/id="ws-(\d+)([A-D])"/);
  const title = html.match(/<title>[^|]*\|\s*Unit (\d{2}), Session ([A-D])/);
  if (header && (Number(header[1]) !== session.unit || header[2] !== session.letter)) {
    problems.push(`${file}: printed header says "${header[0]}"`);
  }
  if (wsId && (Number(wsId[1]) !== session.unit || wsId[2] !== session.letter)) {
    problems.push(`${file}: element id says "${wsId[0]}"`);
  }
  if (title && (Number(title[1]) !== session.unit || title[2] !== session.letter)) {
    problems.push(`${file}: page title says Unit ${title[1]}, Session ${title[2]}`);
  }
}

// 2b. Every unit has a warm-up card, because the interface now links to one from
// every unit. A missing file would be a dead link rather than a quiet omission.
for (let unit = 1; unit <= unitNames.length; unit += 1) {
  const card = `mathnest-unit-${pad(unit)}-warm-up-card.html`;
  if (!existsSync(join(worksheetDir, card))) {
    problems.push(`Missing warm-up card: ${card}. Run node scripts/build-warmups.mjs`);
  }
}

// 3. Units and parts line up.
if (unitNames.length !== phases.length * 4) {
  problems.push(`${unitNames.length} units do not divide into ${phases.length} parts of four.`);
}

// 4. Write the coverage matrix so the repo always carries a current copy.
const byStrand = new Map();
for (const row of rows) {
  if (!byStrand.has(row.strand)) byStrand.set(row.strand, []);
  byStrand.get(row.strand).push(row);
}

let markdown = "# Ontario Grade 2 coverage matrix\n\n";
markdown += "Generated by `node scripts/check-coverage.mjs`. Do not edit by hand.\n\n";
markdown += `Source: https://www.dcp.edu.gov.on.ca/en/curriculum/elementary-mathematics/grades/g2-math\n\n`;
markdown += `${sessions.length} sessions across ${unitNames.length} units. `;
markdown += `${sessions.filter((s) => s.kind === "Core").length} core, `;
markdown += `${sessions.filter((s) => s.kind === "Extension").length} extension, `;
markdown += `${sessions.filter((s) => s.kind === "Review").length} review.\n\n`;

for (const [strand, list] of byStrand) {
  markdown += `## ${strand}\n\n| Code | Expectation | Sessions |\n| --- | --- | --- |\n`;
  for (const row of list) {
    markdown += `| ${row.code} | ${row.summary} | ${row.sessions.join(", ") || "**none**"} |\n`;
  }
  markdown += "\n";
}

markdown += "## Overall expectations\n\n";
markdown += "Mathematical modelling has no specific expectations beneath it in the Ontario\n";
markdown += "document, so it is listed here rather than counted among the specific ones.\n\n";
markdown += "| Code | Expectation | Sessions |\n| --- | --- | --- |\n";
for (const row of overallRows) {
  markdown += `| ${row.code} | ${row.summary} | ${row.sessions.join(", ") || "**none**"} |\n`;
}
markdown += "\n";

markdown += "## Sessions outside the Grade 2 expectations\n\n";
markdown += "These are deliberate extensions or reviews, labelled as such in the interface.\n\n";
markdown += "| Session | Unit | Title | Kind |\n| --- | --- | --- | --- |\n";
for (const session of sessions.filter((s) => s.expectations.length === 0)) {
  markdown += `| ${session.id} | ${unitNames[session.unit - 1]} | ${session.title} | ${session.kind} |\n`;
}

writeFileSync(join(root, "COVERAGE.md"), markdown, "utf8");

if (problems.length) {
  console.error("Coverage check failed:\n");
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

console.log(`Coverage check passed. ${sessions.length} sessions, ${rows.length} expectations, all covered.`);
console.log("Wrote COVERAGE.md");
